def test_deploy_lock_contract_rejects_unhashed_and_forbidden_distributions():
    input_text = "joblib>=1.4,<2\n"
    unhashed_lock = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in --python-version 3.12 --python-platform x86_64-unknown-linux-gnu --generate-hashes --only-binary :all: --output-file requirements.txt
joblib==1.5.3 \\
    --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa \\
    --hash=sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb
anyio==4.14.2
"""
    forbidden_lock = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in --python-version 3.12 --python-platform x86_64-unknown-linux-gnu --generate-hashes --only-binary :all: --output-file requirements.txt
joblib==1.5.3 \\
    --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
rarfile==4.2 \\
    --hash=sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb
"""

    wrong_target_lock = forbidden_lock.replace(
        "--python-platform x86_64-unknown-linux-gnu",
        "--python-platform x86_64-pc-windows-msvc",
    ).replace("rarfile==4.2", "anyio==4.14.2")

    for broken_lock in (unhashed_lock, forbidden_lock, wrong_target_lock):
        with pytest.raises(AssertionError):
            _assert_deploy_lock_contract(input_text, broken_lock)


