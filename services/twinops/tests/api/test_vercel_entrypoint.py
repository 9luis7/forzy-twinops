_MANIFEST_HASH = "sha256:fe2cbd7e1b576f04b2c6380e41ecb7c97df7faa5084c39c4b0d16db786afe7f0"
_MODEL_HASH = "sha256:68d00121edbf8c4c01cf7cd231cd57c4c8eff25661135494e3c791ca78e562ba"
_DEPLOY_FORBIDDEN_DISTRIBUTIONS = {
    "rarfile",
    "scikit-learn",
    "scipy",
    "sklearn",
}
_REQUIREMENT_NAME = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^]]+\])?")
_SHA256_HASH = re.compile(r"^--hash=sha256:[0-9a-f]{64}$")


def _normalized_requirement_name(requirement: str) -> str:
    match = _REQUIREMENT_NAME.match(requirement)
    assert match is not None, f"invalid requirement: {requirement!r}"
    return re.sub(r"[-_.]+", "-", match.group(1)).lower()


def _assert_deploy_lock_contract(input_text: str, lock_text: str) -> None:
    input_requirements = [
        line.strip()
        for line in input_text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    direct_requirements: dict[str, Requirement] = {}
    for requirement_text in input_requirements:
        requirement = Requirement(requirement_text)
        name = _normalized_requirement_name(requirement.name)
        assert name not in direct_requirements, f"duplicate direct requirement: {name}"
        assert requirement.url is None, f"URL requirement is not reproducible: {name}"
        assert requirement.marker is None, f"marker is not allowed in deploy input: {name}"
        assert requirement.specifier, f"direct requirement is unconstrained: {name}"
        direct_requirements[name] = requirement
    direct_names = set(direct_requirements)

    required_command_fragments = (
        "This file was autogenerated by uv",
        "requirements.in",
        "--python-version 3.12",
        "--python-platform x86_64-unknown-linux-gnu",
        "--generate-hashes",
        "--only-binary :all:",
        "--output-file requirements.txt",
    )
    for fragment in required_command_fragments:
        assert fragment in lock_text, f"lock command is missing {fragment!r}"

    hashes_by_distribution: dict[str, list[str]] = {}
    versions_by_distribution: dict[str, Version] = {}
    current_distribution: str | None = None
    for raw_line in lock_text.splitlines():
        line = raw_line.strip().removesuffix("\\").strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("--hash="):
            assert current_distribution is not None
            assert _SHA256_HASH.fullmatch(line), f"invalid lock hash: {line!r}"
            hashes_by_distribution[current_distribution].append(line)
            continue

        distribution_text, separator, version_text = line.partition("==")
        assert separator and distribution_text and version_text, (
            f"unlocked distribution: {line!r}"
        )
        try:
            locked_version = Version(version_text)
        except InvalidVersion as error:
            raise AssertionError(f"invalid locked version: {version_text!r}") from error
        current_distribution = _normalized_requirement_name(distribution_text)
        assert current_distribution not in hashes_by_distribution, (
            f"duplicate locked distribution: {current_distribution}"
        )
        hashes_by_distribution[current_distribution] = []
        versions_by_distribution[current_distribution] = locked_version

    assert hashes_by_distribution, "deploy lock is empty"
    for distribution, hashes in hashes_by_distribution.items():
        assert hashes, f"locked distribution has no hash: {distribution}"

    locked_names = set(hashes_by_distribution)
    missing_direct = direct_names - locked_names
    assert not missing_direct, f"deploy lock is stale: missing {sorted(missing_direct)}"
    for name, requirement in direct_requirements.items():
        locked_version = versions_by_distribution[name]
        assert requirement.specifier.contains(locked_version, prereleases=True), (
            f"locked {name} {locked_version} does not satisfy {requirement.specifier}"
        )
    forbidden = _DEPLOY_FORBIDDEN_DISTRIBUTIONS & (direct_names | locked_names)
    assert not forbidden, f"training/extraction dependency in deploy lock: {sorted(forbidden)}"


